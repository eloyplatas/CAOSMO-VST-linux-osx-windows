#!/usr/bin/env python3
"""Caosmo v0.5 bank: 32 patches built on the SuperCollider-derived engines,
triggers, distributions, stateful LFO waves and spectral FX. Writes factory3.txt."""
import random, os

R = random.Random(505)
def u(a, b): return R.uniform(a, b)
def pick(*xs): return R.choice(xs)
def env(a, d, s, r): return 'eatt=%d edec=%d esus=%.2f erel=%d' % (a, d, s, r)
def space(lvl=0.85): return ['FXA1 type=Reverb p1=%.2f p2=%.2f p3=0.12 p4=0.5 p5=%.2f' % (u(0.7, 0.95), u(0.35, 0.65), lvl)]

out = ['# Caosmo v0.5 bank (generated by presets/gen_v05.py)', '']
def P(name, cat, tags, desc, lines):
    out.append('@ %s | %s | %s | %s' % (name, cat, tags, desc))
    out.extend(lines); out.append('')

# ---------------------------------------------------------------- Stochastic
ST = 'Stochastic'
for name, a, d, ad, dd, pts, tags in [
        ('Xenakis Choir', 0.18, 0.08, 'Cauchy', 'Cauchy', 12, 'Pad;Evolving;Stochastic'),
        ('GENDYN 3', 0.45, 0.25, 'Logist', 'Cauchy', 9, 'Lead;Harsh;Stochastic'),
        ('Polygon Drift', 0.10, 0.04, 'Arcsine', 'Linear', 16, 'Pad;Soft;Stochastic'),
        ('S709', 0.6, 0.45, 'Expon', 'Logist', 6, 'Texture;Harsh;Stochastic')]:
    L = ['L1 engine=Gendy e.ascale=%.2f e.dscale=%.2f e.apar=%.2f e.dpar=%.2f e.spread=%.1f e.points=%d e.stereo=%.2f e.adist=%s e.ddist=%s e.interp=%s %s cut=%d res=%.2f fx1=-8'
         % (a, d, u(0.3, 0.7), u(0.3, 0.7), u(1, 7), pts, u(0.3, 0.7), ad, dd, pick('Linear', 'Cubic'),
            env(int(u(300, 2500)), 1500, 0.85, int(u(1500, 4000))) if 'Pad' in tags else env(5, 600, 0.8, 500),
            u(2500, 8000), u(0.1, 0.3)),
         'LFO1 wave=Brownian rate=%.2f dist=Gauss' % u(0.2, 0.8),
         'LFO2 wave=Markov rate=%.2f' % u(0.5, 3),
         'MOD LFO 1 > L1 Motor 1 : %.2f' % u(0.15, 0.3),
         'MOD LFO 2 > L1 Motor 2 : %.2f' % u(0.1, 0.25),
         'MOD Macro 1 > L1 Motor 1 : 0.4', 'MOD Macro 2 > L1 Motor 2 : 0.4', 'MOD Macro 3 > L1 Motor 5 : 0.4',
         'MOD Macro 4 > L1 Cutoff : -0.35', 'MOD Macro 5 > L1 FX1 Send : 0.45']
    if 'Pad' in tags: L += ['G voices=8', 'L2 engine=Gendy e.ascale=0.12 e.dscale=0.05 e.points=10 e.adist=Cauchy e.ddist=Cauchy pitch=12 level=-9 fx1=-8 ' + env(2000, 1500, 0.8, 3000)]
    else: L += ['G voices=1 legato=1 glide=60']
    P(name, ST, tags, 'Xenakis\' dynamic stochastic synthesis: the wave\'s polygon random-walks every cycle (%s amplitudes, %s durations).' % (ad, dd), L + space())

for name, typ, extra, tags, desc in [
        ('Dust Devils', 'Dust2', 'e.dens=%d e.bpf=0.8 e.q=18' % u(80, 400), 'Texture;Percussive;Stochastic', 'Dust impulses through a key-tracked band-pass: pitched rain.'),
        ('Crackle Box', 'Crackle', 'e.chaos=1.97 e.bpf=0.4 e.q=4', 'Texture;Harsh;Stochastic', 'The Crackle chaos map near breakdown; Macro 1 is the chaos parameter.'),
        ('Gray Code', 'Gray', 'e.bpf=0.9 e.q=25 e.clock=Note_Step', 'Lead;Digital;Stochastic', 'Gray noise clocked by the note and resonated: a buzzing bit-flip lead.'),
        ('Pink Surf', 'Pink', 'e.bpf=0.0 e.tone=-0.3', 'Texture;Soft;Stochastic', 'Pink noise swept by a Noise Ring LFO and spread by Mag Noise.')]:
    L = ['L1 engine=Noise e.type=%s %s e.stereo=%.2f %s cut=%d res=%.2f fx1=-8' % (typ, extra, u(0.4, 0.9), env(5, 400, 0.9, 900), u(3000, 9000), u(0.2, 0.5)),
         'LFO1 wave=Noise_Ring rate=%.2f' % u(0.5, 4),
         'MOD LFO 1 > L1 Cutoff : %.2f' % u(0.2, 0.4),
         'MOD Macro 1 > L1 Motor 3 : 0.4', 'MOD Macro 2 > L1 Motor 2 : 0.4', 'MOD Macro 3 > L1 FX1 Send : 0.45',
         'MOD Macro 4 > L1 Motor 5 : 0.4', 'MOD Macro 5 > FX A2 P1 : 0.5',
         'FXA2 type=Mag_Noise p1=%.2f p2=0.4 p3=0.8' % u(0.3, 0.6)]
    if typ == 'Pink': L += ['L1 ftype=Spring cut=900 res=0.55']
    P(name, ST, tags, desc, L + space())

# trigger-driven patches
for name, mode, action, tags, desc in [
        ('Poisson Rain', 'Dust', 'None', 'Texture;Rhythmic;Stochastic', 'A Dust trigger strikes S&H steps into the filter at random Poisson times.'),
        ('Gauss Clock', 'Gauss', 'Retrig_Envs', 'Rhythmic;Pluck;Stochastic', 'A Gaussian-jittered clock re-strikes the envelopes: a loose, human pulse.'),
        ('Coin Flip Seq', 'Coin', 'Retrig_Envs', 'Rhythmic;Sequence;Stochastic', 'A coin gate on the host 1/16 grid; Macro 1 is the probability.'),
        ('Lorenz Stutter', 'Lorenz', 'Stutter', 'Rhythmic;Glitch;Stochastic', 'A Lorenz-timed trigger fires the stutter and a Wave Loss dropout.')]:
    eng = pick('Maps', 'Gendy')
    e = 'e.map=FBSine e.oct=3 e.a=%.2f e.b=%.2f' % (u(0.3, 0.7), u(0.3, 0.7)) if eng == 'Maps' else 'e.ascale=0.3 e.dscale=0.1 e.points=8'
    L = ['L1 engine=%s %s %s ftype=Ladder cut=%d res=%.2f fx1=-9 fx2=-10' % (eng, e, env(2, 300, 0.4, 300), u(800, 2500), u(0.3, 0.6)),
         'TRIG1 mode=%s rate=%.1f dev=%.2f prob=%.2f shape=S&H_Decay len=%d dist=%s action=%s' % (mode, u(3, 9), u(0.2, 0.6), u(0.6, 0.9), u(80, 300), pick('Gauss', 'Exponential', 'Beta'), action),
         'MOD Trig 1 > L1 Cutoff : %.2f' % u(0.3, 0.5),
         'MOD Trig 1 > L1 Motor 2 : %.2f' % u(0.1, 0.25),
         'MOD Macro 1 > Trig1 Prob : 0.5', 'MOD Macro 2 > Trig1 Rate : 0.4', 'MOD Macro 3 > L1 Motor 2 : 0.35',
         'MOD Macro 4 > L1 Cutoff : -0.35', 'MOD Macro 5 > L1 FX2 Send : 0.45',
         'FXB1 type=Delay p1=0.78 p2=0.45 p5=0.6']
    if mode == 'Coin': L += ['TRIG1 mode=Coin sync=Host div=7']
    if mode == 'Lorenz': L += ['FXB2 type=Wave_Loss p1=0.35 p2=0.4 p3=0.8 opt=1']
    P(name, ST, tags, desc, L + space())

# ------------------------------------------------------------ Neurons & Maps
NM = 'Neurons & Maps'
for name, mp, it, oct, tags, desc in [
        ('Latoo Bells', 'Latoocarfian', 'Cubic', 3, 'Keys;Metallic;Chaotic', 'Pickover\'s Latoocarfian map iterated at 8x the note, cubic-smoothed into bells.'),
        ('Standard Hum', 'Standard', 'Cubic', 2, 'Bass;Chaotic', 'Chirikov\'s standard map: K below 1 hums, above 1 tears.'),
        ('Gingerbread Man', 'Gingerbread', 'Linear', 4, 'Lead;Digital;Chaotic', 'The Gingerbreadman map; A and B move its initial conditions.'),
        ('Cusp Organ', 'Cusp', 'Cubic', 1, 'Keys;Organ;Chaotic', 'The cusp map at one octave over the note: a reedy chaotic organ.'),
        ('LinCong Steps', 'LinCong', 'Step', 5, 'Lead;Digital;Chaotic', 'A linear congruential generator held step by step: 8-bit chaos.'),
        ('Henon Reed', 'Henon', 'Cubic', 3, 'Lead;Reed;Chaotic', 'The Henon map locked to the note with Catmull-Rom interpolation.')]:
    L = ['L1 engine=Maps e.map=%s e.interp=%s e.oct=%d e.a=%.2f e.b=%.2f e.c=%.2f e.d=%.2f e.smooth=%.2f %s ftype=%s cut=%d res=%.2f fx1=-9'
         % (mp, it, oct, u(0.4, 0.6), u(0.4, 0.6), u(0.35, 0.65), u(0.35, 0.65), u(0, 0.3),
            env(3, 900, 0.5, 700) if 'Keys' in tags else env(10, 600, 0.85, 400), *(('Friction', u(120, 400), u(0.5, 0.7)) if R.random() < 0.4 else ('Ladder', u(1500, 6000), u(0.15, 0.4)))),
         'ATTR1 type=%s rate=%.2f smooth=0.4' % (pick('Latoocarfian', 'Standard', 'Henon', 'Gingerbread'), u(0.1, 0.6)),
         'LFO1 wave=Geo_Brownian rate=%.2f dist=Cauchy' % u(0.1, 0.5),
         'MOD Attractor 1 > L1 Motor 2 : %.2f' % u(0.08, 0.18),
         'MOD LFO 1 > L1 Motor 3 : %.2f' % u(0.05, 0.15),
         'MOD Velocity > L1 Cutoff : 0.3',
         'MOD Macro 1 > L1 Motor 2 : 0.35', 'MOD Macro 2 > L1 Motor 3 : 0.35', 'MOD Macro 3 > L1 Motor 1 : 0.3',
         'MOD Macro 4 > L1 Cutoff : -0.35', 'MOD Macro 5 > L1 FX1 Send : 0.45']
    if 'Bass' in tags or 'Lead' in tags: L += ['G voices=1 legato=1 glide=50']
    if mp == 'Henon': L += ['L1 ftype=Friction cut=220 res=0.6']
    P(name, NM, tags, desc, L + space())

for name, model, out_, p1, p2, force, kick, tags, desc in [
        ('Spiking Neuron', 'FitzHugh-Nagumo', 'X', 0.55, 0.4, 0.2, 0.15, 'Lead;Organic;Chaotic', 'A FitzHugh-Nagumo neuron firing in time with the note; Kick makes it misfire.'),
        ('Belousov Clock', 'Oregonator', 'Blend', 0.5, 0.5, 0.0, 0.0, 'Keys;Organic', 'The Oregonator chemical clock (Belousov-Zhabotinsky) tuned to the note.'),
        ('Brusselator Pad', 'Brusselator', 'Y', 0.6, 0.55, 0.35, 0.05, 'Pad;Organic;Evolving', 'A forced Brusselator drifting in and out of its limit cycle.'),
        ('Fox & Hare', 'Lotka-Volterra', 'Blend', 0.45, 0.6, 0.45, 0.25, 'Bass;Organic', 'Predator and prey chasing each other round the note\'s period.'),
        ('ACT Turbulence', 'Arneodo-Coullet-Tresser', 'X', 0.5, 0.5, 0.4, 0.2, 'Texture;Chaotic;Harsh', 'The Arneodo-Coullet-Tresser flow: a chaotic attractor with a pitch.'),
        ('Budworm Outbreak', 'Spruce_Budworm', 'X', 0.6, 0.5, 0.3, 0.1, 'Lead;Digital;Chaotic', 'The spruce budworm population model stepped as a map, outbreak after outbreak.')]:
    pad = 'Pad' in tags
    L = ['L1 engine=Ecosystems e.model=%s e.out=%s e.p1=%.2f e.p2=%.2f e.force=%.2f e.kick=%.2f e.drive=%.2f %s ftype=%s cut=%d res=%.2f fx1=-9'
         % (model, out_, p1, p2, force, kick, u(0.2, 0.5), env(1500, 1500, 0.85, 3000) if pad else env(5, 700, 0.75, 500),
            pick('Ladder', 'Spring', 'LPF'), u(1500, 5000), u(0.15, 0.4)),
         'ATTR1 type=%s rate=%.2f smooth=0.5' % (pick('FitzHugh', 'Lotka-Volterra', 'ACT'), u(0.05, 0.4)),
         'MOD Attractor 1 > L1 Motor 1 : %.2f' % u(0.08, 0.16),
         'MOD Note Random > L1 Motor 2 : 0.12',
         'G nrand_dist=%s' % pick('Gauss', 'Beta', 'Drawn'),
         'MOD Macro 1 > L1 Motor 3 : 0.4', 'MOD Macro 2 > L1 Motor 5 : 0.4', 'MOD Macro 3 > L1 Motor 1 : 0.3',
         'MOD Macro 4 > L1 Cutoff : -0.35', 'MOD Macro 5 > L1 FX1 Send : 0.45']
    if pad: L += ['G voices=8', 'FXA2 type=Diffuse p1=0.5 p2=0.2 p3=0.8', 'DIST 0,-1;0.2,0.8;0.5,-0.6;0.8,0.8;1,-1']
    elif 'Bass' in tags or 'Lead' in tags: L += ['G voices=1 legato=1 glide=40']
    P(name, NM, tags, desc, L + space())

# ----------------------------------------------------------- Bouncing Bodies
BB = 'Bouncing Bodies'
for name, body, grav, bl, dec, ten, tags, desc in [
        ('Ping Pong Drum', 'Circle_Membrane', 8, 0.3, 0.6, 0.0, 'Percussive;Drum', 'A ball dropped on a tuned drum head; it bounces until it settles.'),
        ('Marble Bar', 'Free_Bar', 14, 0.25, 1.4, 0.0, 'Percussive;Mallet', 'A marble rattling on a free bar: a self-playing xylophone note.'),
        ('Bell Drop', 'Bell', 5, 0.4, 3.5, 0.0, 'Percussive;Metallic', 'A ball falling on a bell; scatter moves each bounce.'),
        ('Tabla Physics', 'Circle_Membrane', 20, 0.2, 0.35, 0.6, 'Percussive;Drum', 'High gravity and tension: rapid bounces on a stretched, tabla-like head.'),
        ('Square Skins', 'Square_Membrane', 10, 0.35, 0.9, 0.3, 'Percussive;Drum', 'Square plate modes struck by a trigger-fed ball.'),
        ('Low Gravity', 'Bell', 1.2, 0.15, 6.0, 0.0, 'Texture;Metallic', 'Moon gravity: slow, sparse strikes on a long bell, through Rand Comb.'),
        ('Spring Plate', 'Free_Bar', 6, 0.3, 2.0, 0.2, 'Percussive;Metallic', 'A bar ringing through the hardening Spring filter.'),
        ('Squiz Bounce', 'Circle_Membrane', 12, 0.3, 0.8, 0.1, 'Percussive;Glitch', 'Bouncing drum through the Squiz pitch-shifter.')]:
    L = ['L1 engine=Membrane e.body=%s e.gravity=%.1f e.bloss=%.2f e.height=%.2f e.scatter=%.2f e.decay=%.2f e.strike=%.2f e.tension=%.2f e.modes=%d %s cut=%d res=0.1 fx1=-10'
         % (body, grav, bl, u(0.4, 0.8), u(0.05, 0.3), dec, u(0.3, 0.7), ten, pick(10, 12, 16), env(1, 4000, 1.0, 1500), u(6000, 14000)),
         'MOD Velocity > L1 Motor 3 : 0.3',
         'MOD Macro 1 > L1 Motor 1 : 0.35', 'MOD Macro 2 > L1 Motor 2 : 0.35', 'MOD Macro 3 > L1 Motor 5 : 0.35',
         'MOD Macro 4 > L1 Motor 6 : 0.4', 'MOD Macro 5 > L1 FX1 Send : 0.45']
    if 'Square' in name: L += ['TRIG1 mode=Dust rate=1.5 shape=S&H dist=Uniform', 'MOD Trig 1 > L1 Motor 4 : 0.4']
    if 'Low Gravity' in name: L += ['FXA2 type=Rand_Comb p1=0.35 p2=0.2 p3=0.4 p4=0.8']
    if 'Spring' in name: L += ['L1 ftype=Spring cut=1200 res=0.45']
    if 'Squiz' in name: L += ['FXA2 type=Squiz p1=0.25 p2=0.3 p3=0.8']
    P(name, BB, tags, desc, L + space(0.75))

open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'factory3.txt'), 'w').write('\n'.join(out))
print(sum(1 for l in out if l.startswith('@')), 'presets')
